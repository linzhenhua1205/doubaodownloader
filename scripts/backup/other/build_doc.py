def extract_section(start_pattern, end_pattern=None, max_lines=None):
    """Extract lines between start and end patterns."""
    result = []
    capturing = False
    count = 0
    for line in lines:
        if not capturing:
            if start_pattern in line:
                capturing = True
                result.append(line)
                count += 1
        else:
            if end_pattern and end_pattern in line:
                break
            result.append(line)
            count += 1
            if max_lines and count >= max_lines:
                break
    return result


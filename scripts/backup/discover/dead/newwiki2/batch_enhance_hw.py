def batch_enhance(directory, file_list=None):
    """批量增强目录下的文件"""
    if file_list is None:
        # 获取所有md文件
        file_list = []
        for f in os.listdir(directory):
            if f.endswith('.md') and f != 'index.md':
                file_list.append(f)
    
    enhanced_count = 0
    skipped_count = 0
    
    print(f"\n批量增强目录: {directory}")
    print(f"待处理文件数: {len(file_list)}")
    print("-" * 60)
    
    for filename in file_list:
        filepath = os.path.join(directory, filename)
        if not os.path.exists(filepath):
            print(f"  文件不存在: {filepath}")
            continue
        
        # 从文件名生成标题
        title = filename.replace('.md', '')
        
        try:
            if add_a_level_enhancement(filepath, title):
                enhanced_count += 1
            else:
                skipped_count += 1
        except Exception as e:
            print(f"  处理失败 {filename}: {e}")
    
    print("-" * 60)
    print(f"增强完成: {enhanced_count} 个文件")
    print(f"跳过（已增强）: {skipped_count} 个文件")
    
    return enhanced_count, skipped_count


def extract_original_notes(content):
    notes = []
    pattern = r'## (\d+)\.\s*(.+?)\n\n(.*?)\n\n> `([^`]+)`'
    matches = re.findall(pattern, content, re.DOTALL)
    for num, title, body, source in matches:
        notes.append({
            'num': num,
            'title': title.strip(),
            'body': body.strip(),
            'source': source.strip()
        })
    if not notes:
        pattern2 = r'## (\d+)\.\s*(.+?)\n\n(.*?)\n'
        matches2 = re.findall(pattern2, content, re.DOTALL)
        for num, title, body in matches2[:10]:
            if len(title.strip()) > 0 and len(body.strip()) > 10:
                notes.append({
                    'num': num,
                    'title': title.strip()[:80],
                    'body': body.strip()[:500],
                    'source': '原始笔记'
                })
    return notes


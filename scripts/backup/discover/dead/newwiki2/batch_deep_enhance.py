def process_directory(dirname, max_files=None):
    """处理整个目录"""
    dirpath = BASE_DIR / dirname
    if not dirpath.exists():
        return []
    
    results = []
    md_files = sorted([f for f in dirpath.glob('*.md') if f.name != 'index.md'])
    
    if max_files:
        md_files = md_files[:max_files]
    
    for md_file in md_files:
        success, msg = enhance_file(md_file, dirname)
        results.append((md_file.name, success, msg))
        status = "✓" if success else "○"
        print(f"  {status} {md_file.name}: {msg}")
    
    return results



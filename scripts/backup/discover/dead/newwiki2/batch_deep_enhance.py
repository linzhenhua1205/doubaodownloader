def count_chinese_chars(text):
    return len(re.findall(r'[\u4e00-\u9fff]', text))


def count_words(text):
    chinese = count_chinese_chars(text)
    english = len(re.findall(r'[a-zA-Z]+', text))
    return chinese + english


def extract_frontmatter(text):
    if not text.startswith('---'):
        return {}
    match = re.match(r'^---\n(.*?)\n---', text, re.DOTALL)
    if not match:
        return {}
    fm = {}
    for line in match.group(1).split('\n'):
        if ':' in line:
            key, val = line.split(':', 1)
            fm[key.strip()] = val.strip()
    return fm


def update_frontmatter(text, updates):
    if not text.startswith('---'):
        return text
    match = re.match(r'^---\n(.*?)\n---', text, re.DOTALL)
    if not match:
        return text
    
    fm_text = match.group(1)
    fm = {}
    for line in fm_text.split('\n'):
        if ':' in line:
            key, val = line.split(':', 1)
            fm[key.strip()] = val.strip()
    
    fm.update(updates)
    
    new_fm_lines = []
    for key, value in fm.items():
        new_fm_lines.append(f"{key}: {value}")
    
    new_fm = "---\n" + "\n".join(new_fm_lines) + "\n---"
    return new_fm + text[match.end():]


def get_original_body(content):
    if content.startswith('---'):
        parts = content.split('---', 2)
        if len(parts) >= 3:
            return parts[2].strip()
    return content.strip()


def extract_title(original_body, filename):
    title_match = re.search(r'^#\s+(.+)$', original_body, re.MULTILINE)
    if title_match:
        return title_match.group(1).strip()
    name = os.path.splitext(filename)[0]
    return name



def get_depth_content(category):
    """获取分类的深度内容模板"""
    if category in CATEGORY_DEPTH_CONTENT:
        return CATEGORY_DEPTH_CONTENT[category]
    return DEFAULT_DEPTH_CONTENT


def parse_frontmatter(content):
    if not content.startswith("---"):
        return {}, content
    match = re.match(r"^---\n(.*?)\n---\n", content, re.DOTALL)
    if not match:
        return {}, content
    fm_text = match.group(1)
    body = content[match.end():]
    try:
        fm = yaml.safe_load(fm_text)
        if fm is None:
            fm = {}
    except:
        fm = {}
    return fm, body


def build_frontmatter(fm):
    if not fm:
        return ""
    fm_str = yaml.dump(fm, allow_unicode=True, default_flow_style=False, sort_keys=False).strip()
    return f"---\n{fm_str}\n---\n\n"


def has_section(body, section_name):
    """检查是否有某个章节"""
    pattern = rf'##\s+.*?(技术原理|行业影响|案例补充|实践指南|风险与挑战)'
    return bool(re.search(pattern, body))


def count_missing_sections(body, sections):
    """统计缺少的章节"""
    missing = []
    for sec in sections:
        if not re.search(rf'###\s*[🔬🌍💼🛠️⚠️]?\s*{re.escape(sec)}', body):
            missing.append(sec)
    return missing


def add_depth_sections(body, category, article_type):
    """添加深度内容章节"""
    depth_content = get_depth_content(category)
    
    sections_to_check = ["技术原理", "行业影响", "案例补充", "实践指南", "风险与挑战"]
    missing = count_missing_sections(body, sections_to_check)
    
    if not missing:
        return body, 0
    
    # 根据文章类型决定添加几个章节
    if article_type == 'depth_report':
        add_count = min(3, len(missing))
    elif article_type == 'product_tech':
        add_count = min(2, len(missing))
    else:
        add_count = min(1, len(missing))
    
    # 优先添加的顺序
    priority = ["案例补充", "实践指南", "行业影响", "技术原理", "风险与挑战"]
    to_add = [s for s in priority if s in missing][:add_count]
    
    if not to_add:
        return body, 0
    
    # 在"延伸阅读"之前插入，或者在文章末尾插入
    insert_content = ""
    for sec in to_add:
        insert_content += depth_content[sec] + "\n"
    
    # 找插入位置：在"延伸阅读"或"参考来源"之前
    insert_patterns = [
        r'\n---\n\n##\s*[📚🔗]?\s*延伸阅读',
        r'\n---\n\n##\s*[📚🔗]?\s*知识关联',
        r'\n---\n\n##\s*参考来源',
        r'\n---\n\n##\s*[📚🔗]?\s*相关素材',
    ]
    
    insert_pos = len(body)
    for pattern in insert_patterns:
        match = re.search(pattern, body)
        if match:
            insert_pos = match.start()
            break
    
    body = body[:insert_pos] + insert_content + body[insert_pos:]
    
    return body, len(to_add)


def classify_article_simple(title, body, content_len):
    """简单分类"""
    text = title + " " + body[:300]
    depth_kw = ["全景", "深度", "解析", "报告", "指南", "趋势", "格局", "研报", "洞察", "分析", "研究"]
    news_kw = ["日报", "周报", "月报", "汇总", "动态", "新闻", "资讯", "快讯", "会议", "大会", "峰会", "速递"]
    
    depth_score = sum(1 for kw in depth_kw if kw in text)
    news_score = sum(1 for kw in news_kw if kw in text)
    
    if news_score > depth_score and news_score >= 1:
        return 'news'
    elif depth_score >= 2 or content_len > 3500:
        return 'depth_report'
    else:
        return 'product_tech'



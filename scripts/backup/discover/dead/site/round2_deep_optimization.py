THEME_BACKGROUNDS, THEME_KEY_POINTS, THEME_DEEP_ANALYSIS, THEME_LATEST_NEWS, THEME_CASE_STUDIES = build_theme_data()


def identify_theme(title, content, category):
    title_lower = title.lower()
    content_lower = content[:2000].lower()
    
    theme_scores = {}
    for theme, keywords in THEME_KEYWORDS.items():
        score = 0
        for kw in keywords:
            kw_lower = kw.lower()
            if kw_lower in title_lower:
                score += 3
            if kw_lower in content_lower:
                score += 1
        if score > 0:
            theme_scores[theme] = score
    
    if not theme_scores:
        return None
    
    best_theme = max(theme_scores, key=theme_scores.get)
    if theme_scores[best_theme] >= 2:
        return best_theme
    return None


def get_category_fallback(category):
    category_themes = {
        "AI与机器学习": "大模型",
        "系统与运维": "AIOps",
        "编程与开发": "AI编程",
        "数据库与存储": "向量数据库",
        "云计算": "云原生",
        "知识管理": "知识库",
        "产品与设计": "产品设计",
        "人文社会": "企业管理",
        "行业动态": "科技产业",
        "其他": "科技产业",
    }
    return category_themes.get(category, "科技产业")


def replace_background(content, theme, category):
    bg_theme = theme if theme in THEME_BACKGROUNDS else get_category_fallback(category)
    theme_bg = THEME_BACKGROUNDS.get(bg_theme)
    
    if not theme_bg:
        return content
    
    pattern = r'## 🌐 背景与上下文\s*\n\s*\n.*?(?=\n## |\n---\n|\Z)'
    replacement = f'## 🌐 背景与上下文\n\n{theme_bg}'
    
    new_content = re.sub(pattern, replacement, content, flags=re.DOTALL)
    return new_content


def replace_key_points(content, theme, category):
    kp_theme = theme if theme in THEME_KEY_POINTS else get_category_fallback(category)
    points = THEME_KEY_POINTS.get(kp_theme)
    
    if not points:
        return content
    
    points_text = '\n'.join([f'- {p}' for p in points[:3]])
    
    pattern = r'## 💡 核心要点\s*\n\s*\n.*?(?=\n## |\n---\n|\Z)'
    replacement = f'## 💡 核心要点\n\n{points_text}'
    
    new_content = re.sub(pattern, replacement, content, flags=re.DOTALL)
    return new_content


def replace_deep_analysis(content, theme, category):
    da_theme = None
    if theme and theme in THEME_DEEP_ANALYSIS:
        da_theme = theme
    else:
        cat_theme = get_category_fallback(category)
        if cat_theme in THEME_DEEP_ANALYSIS:
            da_theme = cat_theme
        elif "科技产业" in THEME_DEEP_ANALYSIS:
            da_theme = "科技产业"
    
    if not da_theme:
        return content
    
    deep = THEME_DEEP_ANALYSIS[da_theme]
    
    pattern = r'## 🔍 深度解读\s*\n\s*\n.*?(?=\n## |\n---\n|\Z)'
    replacement = f'## 🔍 深度解读\n\n{deep}'
    
    new_content = re.sub(pattern, replacement, content, flags=re.DOTALL)
    return new_content


def replace_latest_news(content, theme, category):
    ln_theme = theme if theme in THEME_LATEST_NEWS else get_category_fallback(category)
    news = THEME_LATEST_NEWS.get(ln_theme)
    
    if not news:
        return content
    
    news_items = news[:4]
    news_lines = []
    for item in news_items:
        if '：' in item:
            parts = item.split('：', 1)
            news_lines.append(f'- **{parts[0]}**：{parts[1]}')
        else:
            news_lines.append(f'- {item}')
    
    news_text = '\n'.join(news_lines)
    source_line = '\n> 🔍 **数据来源**：行业研究报告、2025-2026年公开数据与趋势分析'
    
    pattern = r'## 🆕 2025-2026 最新进展\s*\n\s*\n.*?(?=\n> 🔍|\n## |\n---\n|\Z)'
    replacement = f'## 🆕 2025-2026 最新进展\n\n{news_text}{source_line}'
    
    new_content = re.sub(pattern, replacement, content, flags=re.DOTALL)
    return new_content


def replace_case_study(content, theme, category):
    if '## 💼 案例补充' not in content:
        return content
    
    cs_theme = None
    if theme and theme in THEME_CASE_STUDIES:
        cs_theme = theme
    else:
        cat_theme = get_category_fallback(category)
        if cat_theme in THEME_CASE_STUDIES:
            cs_theme = cat_theme
    
    if not cs_theme:
        return content
    
    case = THEME_CASE_STUDIES[cs_theme]
    
    pattern = r'## 💼 案例补充\s*\n\s*\n.*?(?=\n## |\n---\n|\Z)'
    replacement = f'## 💼 案例补充\n\n{case}'
    
    new_content = re.sub(pattern, replacement, content, flags=re.DOTALL)
    return new_content


def process_article(filepath, category):
    try:
        content = filepath.read_text(encoding='utf-8')
        title = filepath.stem
    except:
        return False, None
    
    theme = identify_theme(title, content, category)
    
    has_background = '## 🌐 背景与上下文' in content
    has_key_points = '## 💡 核心要点' in content
    has_deep = '## 🔍 深度解读' in content
    has_latest = '## 🆕 2025-2026 最新进展' in content
    
    if not any([has_background, has_key_points, has_deep, has_latest]):
        return False, theme
    
    modified = False
    
    if has_background:
        new_content = replace_background(content, theme, category)
        if new_content != content:
            content = new_content
            modified = True
    
    if has_key_points:
        new_content = replace_key_points(content, theme, category)
        if new_content != content:
            content = new_content
            modified = True
    
    if has_deep:
        new_content = replace_deep_analysis(content, theme, category)
        if new_content != content:
            content = new_content
            modified = True
    
    if has_latest:
        new_content = replace_latest_news(content, theme, category)
        if new_content != content:
            content = new_content
            modified = True
    
    if '## 💼 案例补充' in content:
        new_content = replace_case_study(content, theme, category)
        if new_content != content:
            content = new_content
            modified = True
    
    if modified:
        filepath.write_text(content, encoding='utf-8')
    
    return modified, theme



def clean_old_sections(content):
    lines = content.split('\n')
    result_lines = []
    skip_mode = False
    in_code_block = False
    found_h1 = False
    in_frontmatter = False
    frontmatter_lines = []
    
    for line in lines:
        if line.startswith('---') and not in_frontmatter and not found_h1:
            in_frontmatter = True
            frontmatter_lines.append(line)
            continue
        
        if in_frontmatter:
            frontmatter_lines.append(line)
            if line.startswith('---') and len(frontmatter_lines) > 2:
                in_frontmatter = False
                result_lines.extend(frontmatter_lines)
                result_lines.append('')
            continue
        
        if not found_h1:
            if line.startswith('# '):
                found_h1 = True
                result_lines.append(line)
                result_lines.append('')
            continue
        
        if line.startswith('```'):
            in_code_block = not in_code_block
            result_lines.append(line)
            continue
        
        if in_code_block:
            result_lines.append(line)
            continue
        
        if line.startswith('## '):
            section_title = line[3:].strip()
            clean_title = re.sub(r'^[📌🌟🎭🌐💼🔬📊🎯🏢📚🧬🏗️]+', '', section_title).strip()
            
            if clean_title in old_section_titles:
                skip_mode = True
                continue
            else:
                skip_mode = False
        
        if not skip_mode:
            result_lines.append(line)
    
    result = '\n'.join(result_lines)
    result = re.sub(r'\n{4,}', '\n\n\n', result)
    return result

def update_frontmatter(content, quality_level=None):
    lines = content.split('\n')
    char_count = len(content)
    in_fm = False
    fm_end = -1
    
    for i, line in enumerate(lines):
        if line.startswith('---'):
            if not in_fm:
                in_fm = True
            else:
                fm_end = i
                break
    
    if fm_end == -1:
        return content
    
    for i in range(1, fm_end):
        if lines[i].startswith('word_count:'):
            lines[i] = f'word_count: 约{char_count:,}字'
        if quality_level and lines[i].startswith('quality_level:'):
            lines[i] = f'quality_level: {quality_level}'
    
    return '\n'.join(lines)


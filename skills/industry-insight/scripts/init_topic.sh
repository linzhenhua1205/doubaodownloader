#!/bin/bash
# 新建专题模板 - 行业洞察技能辅助脚本
# Usage: bash <base_dir>/scripts/init_topic.sh <topic-name> [--template|-t <template>]

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SKILL_DIR="$(dirname "$SCRIPT_DIR")"

TOPIC_NAME="${1:-}"
TEMPLATE="${3:-full}"

if [ -z "$TOPIC_NAME" ]; then
    echo "❌ Usage: init_topic.sh <topic-name> [--template full|light|tracking]"
    echo "   Example: init_topic.sh cxl-switch-market"
    exit 1
fi

# 规范化专题名：小写+连字符
TOPIC_SLUG="$(echo "$TOPIC_NAME" | tr '[:upper:]' '[:lower:]' | tr '_' '-' | tr ' ' '-' | sed 's/--*/-/g')"
DATE="$(date +%Y-%m-%d)"
WORKSPACE_DIR="$(cd "$SKILL_DIR/../.." && pwd)"
BASE_DIR="$WORKSPACE_DIR/knowledge/07_industry-research"

echo "🔍 正在创建专题: $TOPIC_SLUG"
echo "📁 路径: $BASE_DIR/"
echo "📅 日期: $DATE"
echo "📋 模板: $TEMPLATE"

# 检查 topic-template 下是否有匹配模板
TEMPLATE_FILE="$BASE_DIR/01_topic-template/$TOPIC_SLUG.md"
if [ -f "$TEMPLATE_FILE" ]; then
    echo "✅ 发现已有专题模板: $TEMPLATE_FILE"
    echo "   建议直接基于模板创建专题文件"
fi

# 创建专题文件
TOPIC_FILE="$BASE_DIR/$TOPIC_SLUG-deep-dive-$DATE.md"

if [ -f "$TOPIC_FILE" ]; then
    echo "⚠️  文件已存在: $TOPIC_FILE"
    echo "   如需更新，直接编辑即可"
    exit 1
fi

cat > "$TOPIC_FILE" << 'METADONE'
# 🏷️ 专题标题

> 专题元信息
> - 创建日期: METADONE
> - 版本: v1.0
> - 跟踪频率: 每周/每月/双周
> - 关联模板: —

---

